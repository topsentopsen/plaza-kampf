/* v2.4: Mobile/PWA/Touch Checks (statisch) */
var assert = require('assert');
var fs = require('fs');
var path = require('path');
var root = path.join(__dirname, '..');
var html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
var ui = fs.readFileSync(path.join(root, 'js/ui.js'), 'utf8');
var man = fs.readFileSync(path.join(root, 'manifest.webmanifest'), 'utf8');
assert.ok(html.indexOf('viewport-fit=cover') !== -1);
assert.ok(html.indexOf('apple-mobile-web-app-capable') !== -1);
assert.ok(html.indexOf('overscroll-behavior') !== -1);
assert.ok(html.indexOf('min-width: 64px') !== -1, 'coarse pointer pad size');
assert.ok(ui.indexOf('pointerdown') !== -1);
assert.ok(ui.indexOf('setPointerCapture') !== -1, 'pointer capture');
assert.ok(ui.indexOf('lostpointercapture') !== -1, 'lostpointercapture');
assert.ok(ui.indexOf('hasPointerCapture') !== -1, 'leave gated by capture');
assert.ok(man.indexOf('display') !== -1);

var main = fs.readFileSync(path.join(root, 'js/main.js'), 'utf8');
assert.ok(main.indexOf('istPwaStandalone') !== -1, 'PWA detect');
assert.ok(main.indexOf('ios-chrome-dismiss') !== -1 || html.indexOf('ios-chrome-dismiss') !== -1, 'chrome dismiss');
assert.ok(html.indexOf('interactive-widget=resizes-content') !== -1, 'interactive-widget');
assert.ok(man.indexOf('"display": "standalone"') !== -1 || man.indexOf('"display":"standalone"') !== -1);
assert.ok(man.indexOf('?v=3.7') !== -1, 'manifest start_url version');
assert.ok(html.indexOf('ctrl-overlay') !== -1, 'overlay css');
assert.ok(html.indexOf('position: fixed !important') !== -1, 'controls fixed overlay');
assert.ok(html.indexOf('image-rendering: auto') !== -1, 'canvas auto render');
assert.ok(main.indexOf('overlayCtrl') !== -1, 'skalieren overlayCtrl');
assert.ok(main.indexOf('maxH = wh - 2') !== -1 || main.indexOf('maxH = wh -2') !== -1, 'no ctrlH subtract in overlay');
assert.ok(html.indexOf('max-height: calc(100dvh - var(--ctrl-h') === -1, 'old ctrl-h max-height gone');
console.log('ok — mobile-touch.test.js (+landscape overlay v3.7)');
